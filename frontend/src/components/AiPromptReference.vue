约束：不要编造未提供的信息；信息不足时请明确指出，并说明需要补充什么。`
  if (!editorForm.value.prompt.trim()) {
    editorForm.value.prompt = framework
  } else {
    editorForm.value.prompt = `${editorForm.value.prompt.trim()}\n\n${framework}`
  }
  nextTick(() => promptTextarea.value?.focus())
}

const insertPromptText = (text: string) => {
  const textarea = promptTextarea.value
  const current = editorForm.value.prompt
  if (!textarea) {
    editorForm.value.prompt = `${current}${current ? '\n' : ''}${text}`
    return
  }
  const start = textarea.selectionStart ?? current.length
  const end = textarea.selectionEnd ?? current.length
  editorForm.value.prompt = `${current.slice(0, start)}${text}${current.slice(end)}`
  nextTick(() => {
    textarea.focus()
    textarea.setSelectionRange(start + text.length, start + text.length)
  })
}

const saveEditor = () => {
  const form = editorForm.value
  const prompt = form.prompt.trim()
  const title = form.title.trim() || inferPromptTitle(prompt)
  const summary = form.summary.trim() || '收藏的自定义提示词，可直接复制到 AI 助手中使用。'
  const category = form.category.trim() || '效率工具'
  const scene = form.scene.trim() || '适合直接复制使用，也可以在需要时继续补充具体任务信息。'
  const tags = editorTags.value
    .split(/[、，,\n]/)
    .map((tag) => tag.trim())
    .filter(Boolean)
    .slice(0, 6)

  if (!prompt) {
    editorError.value = '先粘贴你想收藏的提示词。'
    return
  }

  const nextPrompt: PromptTemplate = {
    id: editingId.value || `custom-${Date.now().toString(36)}`,
    title,
    summary,
    category,
    icon: form.icon.trim() || '✦',
    accent: form.accent.trim() || 'mint',
    tags: tags.length ? tags : ['自定义'],
    scene,
    prompt,
  }

  if (editorMode.value === 'edit') {
    const index = prompts.value.findIndex((item) => item.id === nextPrompt.id)
    if (index >= 0) prompts.value.splice(index, 1, nextPrompt)
  } else {
    prompts.value.unshift(nextPrompt)
  }
  if (selectedPrompt.value?.id === nextPrompt.id) selectedPrompt.value = nextPrompt
  persistPrompts()
  closeEditor()
}

const deletePrompt = (prompt: PromptTemplate) => {
  if (!canDelete.value) return
  prompts.value = prompts.value.filter((item) => item.id !== prompt.id)
  if (!deletedPromptIds.value.includes(prompt.id)) deletedPromptIds.value.push(prompt.id)
  favoriteIds.value = favoriteIds.value.filter((id) => id !== prompt.id)
  persistPrompts()
  persistDeletedPromptIds()
  persistFavorites()
  if (selectedPrompt.value?.id === prompt.id) closePrompt()
  if (editingId.value === prompt.id) closeEditor()
}

const persistFavorites = () => {
  try { localStorage.setItem(favoritesStorageKey.value, JSON.stringify(favoriteIds.value)) } catch {}
}

const toggleFavorite = (id: string) => {
  favoriteIds.value = favoriteIds.value.includes(id)
    ? favoriteIds.value.filter((item) => item !== id)
    : [...favoriteIds.value, id]
  persistFavorites()
}

const copyPrompt = async () => {
  const text = renderedPrompt.value
  try {
    await navigator.clipboard.writeText(text)
  } catch {
    const textarea = document.createElement('textarea')
    textarea.value = text
    textarea.style.position = 'fixed'
    textarea.style.opacity = '0'
    document.body.appendChild(textarea)
    textarea.select()
    document.execCommand('copy')
    textarea.remove()
  }
  copied.value = true
  window.setTimeout(() => { copied.value = false }, 1800)
}

const handleKeydown = (event: KeyboardEvent) => {
  if (event.key === 'Escape' && editorOpen.value) {
    closeEditor()
    return
  }
  if (event.key === 'Escape' && selectedPrompt.value) closePrompt()
}

onMounted(() => {
  authRole.value = localStorage.getItem('auth_role') || ''
  const username = localStorage.getItem('auth_username')?.trim()
  const realName = localStorage.getItem('auth_real_name')?.trim()
  favoriteOwnerKey.value = username || (realName ? `name:${realName}` : 'anonymous')
  loadPrompts()
  try {
    // 旧版全局收藏键不再读取，避免把某个用户的收藏泄露给其他账号。
    const stored = JSON.parse(localStorage.getItem(favoritesStorageKey.value) || '[]')
    if (Array.isArray(stored)) {
      const visibleIds = new Set(prompts.value.map((prompt) => prompt.id))
      favoriteIds.value = stored.filter((id): id is string => typeof id === 'string' && visibleIds.has(id))
      persistFavorites()
    }
  } catch {}
  window.addEventListener('keydown', handleKeydown)
})

onBeforeUnmount(() => {
  window.removeEventListener('keydown', handleKeydown)
  document.body.style.overflow = ''
})
