const loadPrompts = () => {
  try {
    const deleted = JSON.parse(localStorage.getItem(DELETED_PROMPTS_KEY) || '[]')
    if (Array.isArray(deleted)) deletedPromptIds.value = deleted.filter((id): id is string => typeof id === 'string')
    const deletedIds = new Set(deletedPromptIds.value)
    const stored = JSON.parse(localStorage.getItem(PROMPTS_KEY) || 'null')
    if (!Array.isArray(stored)) {
      prompts.value = builtinPrompts.filter((item) => !deletedIds.has(item.id))
      return
    }
    const validStored = stored
      .filter(isPromptTemplate)
      .filter((item) => !deletedIds.has(item.id) && !retiredPromptIds.has(item.id))
      .map((item) => item.category === 'AI 治理' ? { ...item, category: 'AI 常用' } : item)
    const storedById = new Map(validStored.map((item) => [item.id, item]))
    const mergedBuiltins = builtinPrompts
      .filter((item) => !deletedIds.has(item.id))
      .map((item) => storedById.get(item.id) || item)
    const customPrompts = validStored.filter((item) => !builtinPrompts.some((builtin) => builtin.id === item.id))
    prompts.value = [...customPrompts, ...mergedBuiltins]
    persistPrompts()
  } catch {
    prompts.value = builtinPrompts.filter((item) => !deletedPromptIds.value.includes(item.id))
  }
}

